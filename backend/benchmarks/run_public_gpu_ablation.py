def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                     separators=(",", ":"), allow_nan=False).encode()).hexdigest()


def file_digest(path):
    with Path(path).open("rb") as handle:
        return hashlib.file_digest(handle, "sha256").hexdigest()


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def replace_with_retry(temporary, destination, *, timeout_seconds=5.0):
    """Windows readers/antivirus can briefly deny replacement; never discard an unsaved file."""
    deadline = time.monotonic() + timeout_seconds
    delay = 0.01
    while True:
        try:
            Path(temporary).replace(destination)
            return
        except PermissionError:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise
            time.sleep(min(delay, remaining))
            delay = min(delay * 2, 0.2)


def atomic_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8") as handle:
        json.dump(value, handle, ensure_ascii=False, indent=2, allow_nan=False)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    replace_with_retry(temporary, path)


def accumulate_token_telemetry(previous, latest):
    """Count the existing tokenizer pass, without guessing discarded token counts."""
    if not latest:
        return previous or {"status": "unavailable"}
    result = dict(previous or {})
    result["status"] = "measured"
    for field in ("items", "truncated_items", "retained_tokens", "padded_tokens"):
        result[field] = result.get(field, 0) + latest[field]
    result["truncated_fraction"] = result["truncated_items"] / result["items"] if result["items"] else 0
    for field in ("max_length", "padding_mode", "truncation_strategy"):
        result[field] = latest[field]
    return result


class StopRequested(BaseException):
    """Escape production fallback handlers without turning an interrupted job into a result."""


class DegradedResult(RuntimeError):
    def __init__(self, warnings):
        super().__init__("degraded_pipeline_result_rejected")
        self.warnings = warnings


def validate_public_cases(cases):
    """Public benchmark grades may exceed 2; preserve their ordinal gain without remapping."""
    if not isinstance(cases, list) or not cases or any(
        not isinstance(q, dict) or not isinstance(q.get("id"), str) or not q["id"].strip()
        for q in cases
    ):
        raise ValueError("invalid_public_query_id")
    if len({q["id"] for q in cases}) != len(cases):
        raise ValueError("duplicate_or_empty_public_queries")
    for case in cases:
        if not isinstance(case.get("query"), str) or not case["query"].strip():
            raise ValueError("invalid_public_query")
        if not isinstance(case.get("qrels"), dict) or any(
            not isinstance(key, str) or type(value) is not int or not 0 <= value <= 10
            for key, value in case["qrels"].items()
        ):
            raise ValueError("invalid_public_qrels")
        if not any(value > 0 for value in case["qrels"].values()):
            raise ValueError("public_evaluation_requires_positive_qrels")
        cluster = case.get("cluster_id", case["id"])
        if not isinstance(cluster, str) or not cluster.strip():
            raise ValueError("invalid_public_query_cluster")
        if not isinstance(case.get("language"), str) or not case["language"].strip() or case.get("filters"):
            raise ValueError("invalid_public_language_or_filters")


class Budget:
    def __init__(self, output_dir, hours, started_at):
        self.output_dir = Path(output_dir)
        self.deadline = started_at + hours * 3600

    def check(self):
        if (self.output_dir / "STOP").exists():
            raise StopRequested("stop_file")
        if time.time() >= self.deadline:
            raise StopRequested("wall_clock_budget_reached")


class Checkpoint:
    """Transactional records and caches; a failed/incomplete query is never a completed row."""
    def __init__(self, directory):
        self.directory = Path(directory)
        self.directory.mkdir(parents=True, exist_ok=True)
        self.conn = sqlite3.connect(self.directory / "checkpoint.sqlite3", timeout=60)
        self.conn.execute("PRAGMA journal_mode=WAL")
        self.conn.execute("PRAGMA synchronous=FULL")
        self.conn.executescript("""
            CREATE TABLE IF NOT EXISTS cached_json (key TEXT PRIMARY KEY, value TEXT NOT NULL);
            CREATE TABLE IF NOT EXISTS pair_scores (key TEXT PRIMARY KEY, score REAL NOT NULL);
            CREATE TABLE IF NOT EXISTS records (
                job TEXT NOT NULL, experiment TEXT NOT NULL, query_id TEXT NOT NULL,
                record TEXT NOT NULL, PRIMARY KEY(job,experiment,query_id));
            CREATE TABLE IF NOT EXISTS attempts (
                id INTEGER PRIMARY KEY, job TEXT, experiment TEXT, query_id TEXT,
                error_type TEXT NOT NULL, created_at TEXT NOT NULL, details_json TEXT NOT NULL);
            CREATE TABLE IF NOT EXISTS telemetry (
                id INTEGER PRIMARY KEY, kind TEXT NOT NULL, fingerprint TEXT NOT NULL,
                items INTEGER NOT NULL, elapsed_ms REAL NOT NULL, max_length INTEGER NOT NULL);
        """)

    def close(self):
        self.conn.close()

    def get(self, key):
        row = self.conn.execute("SELECT value FROM cached_json WHERE key=?", (key,)).fetchone()
        return json.loads(row[0]) if row else None

    def put(self, key, value):
        with self.conn:
            self.conn.execute("INSERT OR REPLACE INTO cached_json VALUES(?,?)",
                              (key, json.dumps(value, ensure_ascii=False, allow_nan=False)))

    def completed(self, job):
        return {(row[0], row[1]) for row in self.conn.execute(
            "SELECT experiment,query_id FROM records WHERE job=?", (job,))}

    def save_record(self, job, record):
        if record["failed"] or record["degraded"]:
            raise ValueError("failed_or_degraded_record_cannot_be_completed")
        with self.conn:
            self.conn.execute("INSERT INTO records VALUES(?,?,?,?)", (
                job, record["experiment"], record["query_id"],
                json.dumps(record, ensure_ascii=False, allow_nan=False),
            ))

    def records(self, job):
        return [json.loads(row[0]) for row in self.conn.execute(
            "SELECT record FROM records WHERE job=? ORDER BY experiment,query_id", (job,))]

    def failure(self, job, experiment, query_id, error):
        with self.conn:
            self.conn.execute("INSERT INTO attempts(job,experiment,query_id,error_type,created_at,details_json) "
                              "VALUES(?,?,?,?,?,?)", (job, experiment, query_id, type(error).__name__,
                                                     datetime.now(UTC).isoformat(),
                                                     json.dumps({"warnings": getattr(error, "warnings", [])})))

    def timing(self, kind, fingerprint, items, elapsed_ms, max_length, token_telemetry=None):
        with self.conn:
            self.conn.execute("INSERT INTO telemetry(kind,fingerprint,items,elapsed_ms,max_length) "
                              "VALUES(?,?,?,?,?)", (kind, fingerprint, items, elapsed_ms, max_length))
        if token_telemetry:
            key = "token_telemetry:" + digest([kind, fingerprint, max_length])
            self.put(key, accumulate_token_telemetry(self.get(key), token_telemetry))

    def timings(self):
        return [{"kind": row[0], "provider_fingerprint": row[1], "max_length": row[2],
                 "batches": row[3], "items": row[4], "wall_ms": row[5],
                 "token_telemetry": self.get("token_telemetry:" + digest([row[0], row[1], row[2]])),
                 "items_per_second": row[4] * 1000 / row[5] if row[5] else None}
                for row in self.conn.execute("SELECT kind,fingerprint,max_length,count(*),sum(items),"
                                             "sum(elapsed_ms) FROM telemetry GROUP BY kind,fingerprint,max_length")]

    def reliability(self, job):
        counts = {row[0]: row[1] for row in self.conn.execute(
            "SELECT error_type,count(*) FROM attempts WHERE job=? GROUP BY error_type", (job,))}
        warnings = [warning for row in self.conn.execute(
            "SELECT details_json FROM attempts WHERE job=?", (job,))
            for warning in json.loads(row[0]).get("warnings", [])]
        return {"failed_attempts_before_completion": sum(counts.values()),
                "error_types": counts, "degradation_warnings": warnings}


def corpus_fingerprint(corpus):
    value = hashlib.sha256()
    for doc in corpus:
        value.update(json.dumps([doc["id"], doc["title"], doc["text"]], ensure_ascii=False,
                                separators=(",", ":")).encode() + b"\n")
    return value.hexdigest()


def corpus_text(doc):
    return (doc["title"] + "\n" + doc["text"]).strip()


def make_lexical_index(corpus, corpus_hash, cache_dir, budget, progress):
    """Full-corpus FTS5 index with production tokenization; row numbers are stable IDs."""
    directory = Path(cache_dir) / "lexical" / corpus_hash
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / "index.sqlite3"
    conn = sqlite3.connect(path, timeout=60)
    conn.execute("PRAGMA journal_mode=WAL")
    conn.executescript("CREATE VIRTUAL TABLE IF NOT EXISTS terms USING fts5(tokens);"
                       "CREATE TABLE IF NOT EXISTS progress(id INTEGER PRIMARY KEY, rows_done INTEGER);"
                       "INSERT OR IGNORE INTO progress VALUES(1,0);")
    done = conn.execute("SELECT rows_done FROM progress WHERE id=1").fetchone()[0]
    if done > len(corpus):
        raise ValueError("lexical_progress_exceeds_corpus")
    while done < len(corpus):
        budget.check()
        stop = min(done + 2000, len(corpus))
        with conn:
            conn.executemany("INSERT INTO terms(rowid,tokens) VALUES(?,?)", (
                (index + 1, search_tokens(corpus_text(corpus[index]))) for index in range(done, stop)
            ))
            conn.execute("UPDATE progress SET rows_done=? WHERE id=1", (stop,))
        done = stop
        progress("lexical_index", done=done, total=len(corpus))
    return conn


def encode_corpus(corpus, corpus_hash, provider, max_length, batch_size,
                  cache_dir, checkpoint, budget, progress):
    """Flush vectors before committing row offset; a crash can only repeat the last batch."""
    import numpy as np

    identity = {"corpus_sha256": corpus_hash, "provider": provider.fingerprint,
                "max_length": max_length, "text_format": "title_newline_text_v1",
                "purpose": "passage", "dtype": "float32", "batch_size": batch_size}
    key = digest(identity)
    directory = Path(cache_dir) / "vectors" / key
    directory.mkdir(parents=True, exist_ok=True)
    state_path, vector_path = directory / "state.json", directory / "vectors.npy"
    state = read_json(state_path) if state_path.exists() else {"identity": identity, "rows_done": 0}
    if state["identity"] != identity:
        raise ValueError("vector_cache_fingerprint_mismatch")
    done = state["rows_done"]
    if done and not vector_path.exists():
        raise ValueError("vector_cache_file_missing")
    vectors = np.load(vector_path, mmap_mode="r+") if vector_path.exists() else None
    if vectors is not None and (vectors.shape[0] != len(corpus) or vectors.dtype != np.float32):
        raise ValueError("vector_cache_shape_mismatch")
    if done > len(corpus):
        raise ValueError("vector_progress_exceeds_corpus")
    if state.get("completed") and state.get("vectors_sha256") != file_digest(vector_path):
        raise ValueError("vector_cache_content_hash_mismatch")
    current_session_proven = False
    while done < len(corpus):
        budget.check()
        stop = min(done + batch_size, len(corpus))
        texts = [corpus_text(doc) for doc in corpus[done:stop]]
        started = time.perf_counter()
        encoded = np.asarray(provider.encode(texts, query=False, max_length=max_length,
                                             batch_size=batch_size), dtype=np.float32)
        elapsed = (time.perf_counter() - started) * 1000
        if encoded.ndim != 2 or encoded.shape[0] != len(texts) or not np.isfinite(encoded).all():
            raise ValueError("invalid_real_embedding_batch")
        if not np.allclose(np.linalg.norm(encoded, axis=1), 1, atol=1e-3):
            raise ValueError("embedding_provider_must_normalize")
        if vectors is None:
            vectors = np.lib.format.open_memmap(vector_path, mode="w+", dtype=np.float32,
                                               shape=(len(corpus), encoded.shape[1]))
        if encoded.shape[1] != vectors.shape[1]:
            raise ValueError("embedding_dimension_changed")
        vectors[done:stop] = encoded
        vectors.flush()
        token_telemetry = getattr(provider, "last_call_telemetry", None)
        checkpoint.timing("passage_gpu_encode", digest(provider.fingerprint), len(texts), elapsed,
                          max_length, token_telemetry)
        state["token_telemetry"] = accumulate_token_telemetry(state.get("token_telemetry"), token_telemetry)
        state.update(rows_done=stop, shape=list(vectors.shape), completed=False)
        if not current_session_proven:
            state["gpu_proof"] = provider.prove_gpu_execution()
            current_session_proven = True
        atomic_json(state_path, state)
        done = stop
        progress("passage_encode", done=done, total=len(corpus), model=provider.fingerprint,
                 max_length=max_length, batch_wall_ms=elapsed)
    if not state.get("completed"):
        state.update(completed=True, vectors_sha256=file_digest(vector_path))
        atomic_json(state_path, state)
    if not state.get("gpu_proof"):
        raise ValueError("vector_cache_lacks_complete_gpu_proof")
    proof = state["gpu_proof"] | {"passage_token_telemetry": state.get("token_telemetry")}
    return np.load(vector_path, mmap_mode="r"), key, proof


def exact_top_k(scores, limit):
    """Exact cosine ranking with stable index tie breaking, including ties at the cutoff."""
    import numpy as np

    scores = np.asarray(scores)
    if scores.ndim != 1 or not np.isfinite(scores).all():
        raise ValueError("invalid_dense_scores")
    if len(scores) <= limit:
        selected = np.arange(len(scores))
    else:
        boundary = np.partition(scores, len(scores) - limit)[len(scores) - limit]
        selected = np.flatnonzero(scores >= boundary)
    order = np.lexsort((selected, -scores[selected]))
    return selected[order[:limit]]


class CachedStore:
    """Real lexical retrieval and exact vector scan behind the existing pipeline interface."""
    def __init__(self, corpus, corpus_hash, lexical_conn, vectors, vector_key, encoder,
                 max_length, checkpoint, budget, cache_limit=500):
        self.corpus = corpus
        self.corpus_hash = corpus_hash
        self.lexical_conn = lexical_conn
        self.vectors = vectors
        self.vector_key = vector_key
        self.encoder = encoder
        self.max_length = max_length
        self.checkpoint = checkpoint
        self.budget = budget
        self.cache_limit = cache_limit
        self.hits = {"lexical": 0, "dense": 0, "query_vectors": 0}
        self.misses = {key: 0 for key in self.hits}

    def candidates(self, pairs, limit):
        return [Candidate(chunk_id=index + 1, document_id=self.corpus[index]["id"],
                          title=self.corpus[index]["title"], text=self.corpus[index]["text"], score=score)
                for index, score in pairs[:limit]]

    def lexical(self, query, filters, limit):
        if filters or limit > self.cache_limit:
            raise ValueError("unsupported_public_filter_or_candidate_limit")
        self.budget.check()
        tokens = lexical_query_tokens(query)
        key = "lexical:" + digest([self.corpus_hash, tokens, self.cache_limit, "fts5_bm25_v1"])
        pairs = self.checkpoint.get(key)
        if pairs is None:
            self.misses["lexical"] += 1
            expression = " OR ".join('"' + token + '"' for token in tokens)
            started = time.perf_counter()
            pairs = [(row[0] - 1, -row[1]) for row in self.lexical_conn.execute(
                "SELECT rowid,bm25(terms) AS rank FROM terms WHERE terms MATCH ? "
                "ORDER BY rank,rowid LIMIT ?", (expression, self.cache_limit),
            )] if expression else []
            self.checkpoint.timing("lexical_uncached", self.corpus_hash, 1,
                                   (time.perf_counter() - started) * 1000, 0)
            self.checkpoint.put(key, pairs)
        else:
            self.hits["lexical"] += 1
        return self.candidates(pairs, limit)

    def dense(self, query, filters, limit):
        import numpy as np

        if filters or limit > self.cache_limit:
            raise ValueError("unsupported_public_filter_or_candidate_limit")
        self.budget.check()
        key = "dense:" + digest([self.vector_key, query, self.cache_limit, "exact_dot_v1"])
        pairs = self.checkpoint.get(key)
        if pairs is None:
            self.misses["dense"] += 1
            query_key = "query_vector:" + digest([self.encoder.fingerprint, self.max_length, query, 1, "query"])
            query_vector = self.checkpoint.get(query_key)
            if query_vector is None:
                self.misses["query_vectors"] += 1
                started = time.perf_counter()
                encoded = self.encoder.encode([query], query=True, max_length=self.max_length, batch_size=1)
                self.encoder.prove_gpu_execution()
                query_vector = np.asarray(encoded[0], dtype=np.float32).tolist()
                self.checkpoint.timing("query_gpu_encode", digest(self.encoder.fingerprint), 1,
                                       (time.perf_counter() - started) * 1000, self.max_length,
                                       getattr(self.encoder, "last_call_telemetry", None))
                self.checkpoint.put(query_key, query_vector)
            else:
                self.hits["query_vectors"] += 1
            started = time.perf_counter()
            vector = np.asarray(query_vector, dtype=np.float32)
            if vector.shape != (self.vectors.shape[1],) or not np.isfinite(vector).all():
                raise ValueError("invalid_query_vector")
            scores = self.vectors @ vector
            indexes = exact_top_k(scores, self.cache_limit)
            pairs = [(int(index), float(scores[index])) for index in indexes]
            self.checkpoint.timing("dense_cpu_exact_scan", self.vector_key, 1,
                                   (time.perf_counter() - started) * 1000, self.max_length)
            self.checkpoint.put(key, pairs)
        else:
            self.hits["dense"] += 1
        return self.candidates(pairs, limit)


class CachedReranker:
    def __init__(self, provider, checkpoint, budget, max_length, batch_size, on_proof=None):
        self.provider, self.checkpoint, self.budget = provider, checkpoint, budget
        self.max_length, self.batch_size = max_length, batch_size
        self.hits = self.misses = 0
        self.proof = checkpoint.get("rerank_proof:" + digest(provider.fingerprint))
        self.current_session_proven = False
        self.on_proof = on_proof
        if self.proof and on_proof:
            on_proof(self.proof)

    def __call__(self, query, rows):
        keys = [digest([self.provider.fingerprint, self.max_length, self.batch_size, query,
                        row.title + "\n" + row.text]) for row in rows]
        scores, missing = {}, []
        for index, key in enumerate(keys):
            cached = self.checkpoint.conn.execute("SELECT score FROM pair_scores WHERE key=?", (key,)).fetchone()
            if cached:
                self.hits += 1
                scores[index] = cached[0]
            else:
                self.misses += 1
                missing.append(index)
        for offset in range(0, len(missing), self.batch_size):
            self.budget.check()
            indexes = missing[offset:offset + self.batch_size]
            texts = [rows[index].title + "\n" + rows[index].text for index in indexes]
            started = time.perf_counter()
            values = self.provider.score(query, texts, max_length=self.max_length, batch_size=self.batch_size)
            elapsed = (time.perf_counter() - started) * 1000
            if len(values) != len(indexes) or any(not math.isfinite(float(value)) for value in values):
                raise ValueError("invalid_real_rerank_scores")
            if not self.current_session_proven:
                proof = self.provider.prove_gpu_execution()
                self.checkpoint.put("rerank_proof:" + digest(self.provider.fingerprint), proof)
                self.proof = proof
                self.current_session_proven = True
                if self.on_proof:
                    self.on_proof(proof)
            with self.checkpoint.conn:
                for index, value in zip(indexes, values, strict=True):
                    scores[index] = float(value)
                    self.checkpoint.conn.execute("INSERT OR REPLACE INTO pair_scores VALUES(?,?)", (keys[index], float(value)))
            self.checkpoint.timing("pair_gpu_rerank", digest(self.provider.fingerprint), len(indexes), elapsed,
                                   self.max_length, getattr(self.provider, "last_call_telemetry", None))
        return [scores[index] for index in range(len(rows))]


def measure_query(store, case, experiment, rerank):
    """One quality observation. Failures propagate and are not filled with zero rankings."""
    result = run_ablation(store, case["query"], experiment, rewrite=RuleQueryRewriter(), rerank=rerank)
    if result["warnings"]:
        raise DegradedResult(result["warnings"])
    rows = result.pop("results")
    ids = [row.document_id for row in rows]
    positives = {key for key, grade in case["qrels"].items() if grade > 0}
    candidate_ids = set(result["trace"]["candidate_document_ids"])
    pool_ids = set(result["trace"]["rerank_document_ids"])
    for branch in result["trace"]["branches"]:
        branch["qrel_recall"] = len(positives & set(branch["document_ids"])) / len(positives) if positives else None
    def oracle_ndcg(ids):
        ordered = sorted(ids, key=lambda document_id: (-case["qrels"].get(document_id, 0), document_id))
        return metrics(ordered, case["qrels"], 10)["ndcg_at_k"] if positives else None
    return result | {
        "experiment": experiment.id, "query_id": case["id"], "repeat": 0,
        "language": case["language"], "cluster_id": case.get("cluster_id", case["id"]),
        "control_type": "unspecified", "failed": False, "degraded": False,
        "ids": ids, "returned_count": len(ids), "answerable": bool(positives),
        "ranking": [{"document_id": row.document_id, "chunk_id": row.chunk_id,
                     "score": row.score, "page": row.page} for row in rows],
        "metrics": {str(k): metrics(ids, case["qrels"], k) for k in (1, 3, 5, 10)} if positives else None,
        "candidate_recall": len(positives & candidate_ids) / len(positives) if positives else None,
        "rerank_pool_recall": len(positives & pool_ids) / len(positives) if positives and experiment.rerank else None,
        "candidate_oracle_ndcg@10": oracle_ndcg(candidate_ids),
        "rerank_pool_oracle_ndcg@10": oracle_ndcg(pool_ids) if experiment.rerank else None,
        "latency_kind": "cache_assisted_pipeline_wall_time_not_end_to_end_inference_latency",
    }


def write_job_report(output_dir, job, job_description, records, experiments, cases, matrix,
                     checkpoint, gpu_proofs):
    expected = {(e.id, q["id"]) for e in experiments for q in cases}
    observed = {(r["experiment"], r["query_id"]) for r in records}
    if observed != expected or len(records) != len(expected):
        raise ValueError("cannot_publish_incomplete_job_as_completed")
    required_models = {job_description["embedding_model"]}
    if any(e.rerank and e.id != "rrf_rerank_english" for e in experiments):
        required_models.add(matrix["reranker_model"])
    if any(e.id == "rrf_rerank_english" for e in experiments):
        required_models.add(matrix["alternative_reranker_model"])
    if any(not gpu_proofs.get(model) for model in required_models):
        raise ValueError("completed_job_requires_all_gpu_proofs")
    report = {
        "protocol": {"repeats": 1, "warmup_passes": 0, "seed": matrix["seed"],
                     "schedule": "seeded_query_order_with_cached_actual_provider_scores",
                     "independent_questions": len(cases),
                     "answerable_questions": sum(any(v > 0 for v in q["qrels"].values()) for q in cases),
                     "top_ks": [1, 3, 5, 10],
                     "timing_kind": "cache_assisted_replay; see separate real_inference_telemetry"},
        "experiments": [asdict(e) for e in experiments], "records": records, "warmups": [],
    }
    summary = public_summary(report, contrasts=matrix["contrasts"],
                             bootstrap_samples=matrix["bootstrap_samples"], seed=matrix["seed"])
    summary.update(status="completed", job=job_description, job_fingerprint=job,
                   gpu_proofs=gpu_proofs, real_inference_telemetry=checkpoint.timings(),
                   real_inference_telemetry_scope="cumulative_campaign_through_this_job_completion",
                   reliability=checkpoint.reliability(job),
                   completed_at=datetime.now(UTC).isoformat())
    summary["retrieval_backends"] = {
        "lexical": "SQLite FTS5 BM25 over production search_tokens and lexical_query_tokens; not PostgreSQL ts_rank",
        "dense": "Exact CPU cosine/dot scan of normalized vectors produced by the verified GPU encoder",
        "rerank": "Verified GPU ONNX cross-encoder raw logits, cached by model/query/document/token budget",
    }
    summary["rewrite_diagnostics"] = {}
    for experiment in experiments:
        rows = [record for record in records if record["experiment"] == experiment.id]
        counts = [len(record["queries"]) for record in rows]
        summary["rewrite_diagnostics"][experiment.id] = {
            "rewrite_enabled": experiment.rewrite, "queries": len(rows),
            "queries_with_additional_variants": sum(count > 1 for count in counts),
            "additional_variant_fraction": sum(count > 1 for count in counts) / len(rows),
            "mean_variants": sum(counts) / len(counts),
        }
    summary["limitations"] = [
        "Pipeline p50/p95 mix cold provider calls and cached-score replay, NOT end-to-end online inference latency.",
        "Embedding and rerank telemetry measures actual uncached GPU calls separately; provider initialization is excluded.",
        "Dense search is an exact CPU dot-product scan of real GPU-generated vectors; no GPU ANN throughput claim.",
        "Document title plus text is truncated by each encoder tokenizer; there is no passage chunking or document aggregation.",
        "One observation per query/config; no pseudoreplication through replay. Paired CIs resample queries/clusters.",
        "Only retrieval quality is evaluated; no generated answers, faithfulness or production-library quality is measured.",
        "Unjudged documents count as zero. T2 dev data is exploratory, not a held-out test claim.",
        "Source-policy experiments are not part of this public-corpus retrieval runner.",
    ]
    directory = Path(output_dir) / "jobs" / job
    directory.mkdir(parents=True, exist_ok=True)
    trace_path = directory / "query_results.jsonl"
    temporary = trace_path.with_suffix(".jsonl.tmp")
    with temporary.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False, allow_nan=False) + "\n")
        handle.flush()
        os.fsync(handle.fileno())
    replace_with_retry(temporary, trace_path)
    indexed = {(record["experiment"], record["query_id"]): record for record in records}
    delta_path = directory / "query_deltas.jsonl"
    temporary = delta_path.with_suffix(".jsonl.tmp")
    signatures = []
    with temporary.open("w", encoding="utf-8") as handle:
        for contrast in matrix["contrasts"]:
            counts = {"improved_with_candidate_recall_gain": 0, "improved_without_candidate_recall_gain": 0,
                      "worsened_with_candidate_recall_loss": 0, "worsened_without_candidate_recall_loss": 0}
            for case in cases:
                current = indexed.get((contrast["experiment"], case["id"]))
                previous = indexed.get((contrast["reference"], case["id"]))
                if current is None or previous is None or not current["metrics"]:
                    continue
                delta = current["metrics"]["10"]["ndcg_at_k"] - previous["metrics"]["10"]["ndcg_at_k"]
                candidate_delta = current["candidate_recall"] - previous["candidate_recall"]
                if delta > 1e-12:
                    counts["improved_with_candidate_recall_gain" if candidate_delta > 1e-12
                           else "improved_without_candidate_recall_gain"] += 1
                elif delta < -1e-12:
                    counts["worsened_with_candidate_recall_loss" if candidate_delta < -1e-12
                           else "worsened_without_candidate_recall_loss"] += 1
                def positive_ranks(record, qrels=case["qrels"]):
                    return {doc_id: rank for rank, doc_id in enumerate(record["ids"], 1)
                            if qrels.get(doc_id, 0) > 0}
                diagnostic = {**contrast, "query_id": case["id"], "language": case["language"],
                              "ndcg@10_delta": delta, "candidate_recall_delta": candidate_delta,
                              "before_positive_ranks": positive_ranks(previous),
                              "after_positive_ranks": positive_ranks(current),
                              "before_ids": previous["ids"], "after_ids": current["ids"],
                              "before_candidate_oracle_ndcg@10": previous["candidate_oracle_ndcg@10"],
                              "after_candidate_oracle_ndcg@10": current["candidate_oracle_ndcg@10"],
                              "before_rerank_pool_recall": previous["rerank_pool_recall"],
                              "after_rerank_pool_recall": current["rerank_pool_recall"]}
                handle.write(json.dumps(diagnostic, ensure_ascii=False, allow_nan=False) + "\n")
            signatures.append(contrast | counts)
        handle.flush()
        os.fsync(handle.fileno())
    replace_with_retry(temporary, delta_path)
    summary["observed_change_signatures"] = signatures
    summary["attribution_limit"] = "Candidate coverage and positive-rank movements are observed signatures, not a proof of semantic cause; inspect per-query qrels and traces."
    atomic_json(directory / "summary.json", summary)
    return summary


def code_fingerprint():
    names = [Path(__file__), BACKEND / "benchmarks/gpu_onnx.py",
             BACKEND / "benchmarks/public_benchmark_data.py"]
    names += [BACKEND / "src/research_agent" / name for name in (
        "rag_ablation.py", "retrieval_lab.py", "retrieval_providers.py", "pg_lab.py", "store.py", "hub_query.py")]
    return {path.relative_to(BACKEND).as_posix(): file_digest(path) for path in names}


def progress_writer(output_dir):
    last_print = 0.0

    def progress(phase, **fields):
        nonlocal last_print
        record = {"status": "running", "phase": phase, "updated_at": datetime.now(UTC).isoformat(), **fields}
        atomic_json(Path(output_dir) / "progress.json", record)
        if time.monotonic() - last_print >= 15 or fields.get("done") == fields.get("total"):
            printable = {key: value for key, value in record.items() if key != "model"}
            print(json.dumps(printable, ensure_ascii=False), flush=True)
            last_print = time.monotonic()
    return progress


def joint_memory_smoke(encoder_class, reranker_class, args, matrix, specs, texts, query):
    """Exercise the same simultaneous GPU residency as the full worker, before a long run."""
    import numpy as np

    encoder_id, reranker_id = "e5_small", matrix["reranker_model"]
    batch = texts[:8]
    encoder = encoder_class(args.models_dir / encoder_id, specs[encoder_id])
    # Full evaluation keeps the already-used encoder arena alive while loading a reranker.
    encoder.encode(batch, query=False, max_length=512, batch_size=8)
    reranker = reranker_class(args.models_dir / reranker_id, specs[reranker_id])
    try:
        started = time.perf_counter()
        vectors = np.asarray(encoder.encode(batch, query=False, max_length=512, batch_size=8))
        embedding_ms = (time.perf_counter() - started) * 1000
        embedding_tokens = getattr(encoder, "last_call_telemetry", None)
        started = time.perf_counter()
        scores = reranker.score(query, batch, max_length=512, batch_size=8)
        rerank_ms = (time.perf_counter() - started) * 1000
        if vectors.ndim != 2 or vectors.shape[0] != len(batch) or not np.isfinite(vectors).all():
            raise ValueError("joint_pilot_invalid_embedding_output")
        if len(scores) != len(batch) or not all(math.isfinite(float(value)) for value in scores):
            raise ValueError("joint_pilot_invalid_rerank_output")
        return {
            "model": encoder_id + "+" + reranker_id,
            "kind": "joint_embedding_rerank_memory_smoke", "max_length": 512,
            "batch_size": 8, "items": len(batch), "embedding_shape": list(vectors.shape),
            "wall_ms": embedding_ms + rerank_ms,
            "embedding_wall_ms": embedding_ms, "rerank_wall_ms": rerank_ms,
            "items_per_second": len(batch) * 1000 / (embedding_ms + rerank_ms),
            "simultaneous_sessions": [encoder_id, reranker_id],
            "encoder_preallocated_before_reranker_load": True,
            "gpu_proof": {encoder_id: encoder.prove_gpu_execution(),
                          reranker_id: reranker.prove_gpu_execution()},
            "fingerprint": {encoder_id: encoder.fingerprint, reranker_id: reranker.fingerprint},
            "token_telemetry": {encoder_id: embedding_tokens,
                                reranker_id: getattr(reranker, "last_call_telemetry", None)},
            "limitation": "Successful joint inference proves this batch fits at pilot time, not a VRAM peak or stress-test guarantee.",
        }
    finally:
        del reranker, encoder
        gc.collect()


def pilot(args, matrix, specs):
    from gpu_onnx import OnnxCrossEncoder, OnnxTextEncoder
    from public_benchmark_data import load_prepared_dataset

    corpus, queries, manifest = load_prepared_dataset(args.data_dir / matrix["datasets"][0])
    indexes = sorted({round(i * (len(corpus) - 1) / 15) for i in range(min(16, len(corpus)))})
    texts = [corpus_text(corpus[index]) for index in indexes]
    observations = []
    selected_models = set(args.pilot_models) if args.pilot_models else None
    for model_id in matrix["embedding_models"]:
        if selected_models is not None and model_id not in selected_models:
            continue
        provider = OnnxTextEncoder(args.models_dir / model_id, specs[model_id])
        for length in matrix["max_lengths"]:
            started = time.perf_counter()
            provider.encode(texts, query=False, max_length=length, batch_size=matrix["embedding_batch_size"])
            elapsed = (time.perf_counter() - started) * 1000
            proof = provider.prove_gpu_execution()
            observations.append({"model": model_id, "kind": "embed", "max_length": length,
                                 "items": len(texts), "wall_ms": elapsed,
                                 "items_per_second": len(texts) * 1000 / elapsed, "gpu_proof": proof,
                                 "token_telemetry": getattr(provider, "last_call_telemetry", None),
                                 "fingerprint": provider.fingerprint})
        del provider
        gc.collect()
    if not args.pilot_models:
        observations.append(joint_memory_smoke(OnnxTextEncoder, OnnxCrossEncoder, args, matrix,
                                              specs, texts, queries[0]["query"]))
    for model_id in dict.fromkeys([matrix["reranker_model"], matrix["alternative_reranker_model"]]):
        if selected_models is not None and model_id not in selected_models:
            continue
        provider = OnnxCrossEncoder(args.models_dir / model_id, specs[model_id])
        started = time.perf_counter()
        scores = provider.score(queries[0]["query"], texts[:8], max_length=512, batch_size=matrix["rerank_batch_size"])
        elapsed = (time.perf_counter() - started) * 1000
        if len(scores) != min(8, len(texts)) or not all(math.isfinite(v) for v in scores):
            raise ValueError("pilot_invalid_rerank_output")
        observations.append({"model": model_id, "kind": "rerank", "max_length": 512,
                             "items": len(scores), "wall_ms": elapsed,
                             "items_per_second": len(scores) * 1000 / elapsed,
                             "gpu_proof": provider.prove_gpu_execution(), "fingerprint": provider.fingerprint})
        observations[-1]["token_telemetry"] = getattr(provider, "last_call_telemetry", None)
        del provider
        gc.collect()
    result = {"status": "pilot_completed", "created_at": datetime.now(UTC).isoformat(),
              "dataset_manifest": manifest, "observations": observations,
              "limitation": "Tiny cold pilot includes initial shape compilation; throughput is not a full-corpus estimate."}
    atomic_json(args.output_dir / "pilot.json", result)
    print(json.dumps({"status": result["status"], "observations": len(observations)}, ensure_ascii=False))
    return 0


def run(args, matrix, specs):
    from gpu_onnx import OnnxCrossEncoder, OnnxTextEncoder
    from public_benchmark_data import load_prepared_dataset

    args.output_dir.mkdir(parents=True, exist_ok=True)
    checkpoint = Checkpoint(args.output_dir)
    progress = progress_writer(args.output_dir)
    source_hashes = code_fingerprint()
    dataset_inputs = {name: read_json(args.data_dir / name / "manifest.json")
                      for name in matrix["datasets"]}
    input_locations = {"models_dir": str(args.models_dir.resolve()), "data_dir": str(args.data_dir.resolve())}
    fingerprint = digest({"matrix": matrix, "models": specs, "sources": source_hashes,
                          "dataset_manifests": dataset_inputs, "input_locations": input_locations})
    state_path = args.output_dir / "run_state.json"
    state = read_json(state_path) if state_path.exists() else {
        "fingerprint": fingerprint, "started_epoch": time.time(), "completed_jobs": [],
        "matrix": matrix, "models": specs, "source_sha256": source_hashes,
        "dataset_manifests": dataset_inputs, "input_locations": input_locations,
        "runtime": {"python": platform.python_version(), "system": platform.system(),
                    "sqlite": sqlite3.sqlite_version},
    }
    if state["fingerprint"] != fingerprint:
        raise ValueError("run_fingerprint_changed_use_new_output_directory")
    budget = Budget(args.output_dir, args.budget_hours or matrix["budget_hours"], state["started_epoch"])
    state["status"] = "running"
    atomic_json(state_path, state)
    active_job = active_experiment = active_query = None
    try:
        experiments = [Experiment(**value) for value in matrix["experiments"]]
        if max(e.candidate_limit for e in experiments) > matrix["candidate_cache_limit"]:
            raise ValueError("cache_limit_below_experiment_budget")
        for dataset_name in matrix["datasets"]:
            budget.check()
            progress("load_dataset", dataset=dataset_name)
            corpus, cases, dataset_manifest = load_prepared_dataset(args.data_dir / dataset_name)
            validate_public_cases(cases)
            if not corpus or len({doc["id"] for doc in corpus}) != len(corpus):
                raise ValueError("invalid_public_corpus_ids")
            doc_ids = {doc["id"] for doc in corpus}
            if any(set(case["qrels"]) - doc_ids for case in cases):
                raise ValueError("public_qrels_outside_full_corpus")
            corpus_hash = corpus_fingerprint(corpus)
            lexical_conn = make_lexical_index(corpus, corpus_hash, args.output_dir / "cache", budget, progress)
            for model_id in matrix["embedding_models"]:
                encoder = None
                for max_length in matrix["max_lengths"]:
                    description = {"dataset": dataset_name, "embedding_model": model_id,
                                   "max_length": max_length, "corpus_sha256": corpus_hash,
                                   "corpus_count": len(corpus), "query_count": len(cases),
                                   "query_sha256": digest(cases), "dataset_manifest": dataset_manifest,
                                   "run_fingerprint": fingerprint}
                    job = digest(description)
                    active_job = job
                    active_experiment = active_query = None
                    if job in state["completed_jobs"]:
                        summary_path = args.output_dir / "jobs" / job / "summary.json"
                        if not summary_path.exists() or read_json(summary_path)["status"] != "completed":
                            raise ValueError("completed_job_report_missing")
                        continue
                    if encoder is None:
                        budget.check()
                        encoder = OnnxTextEncoder(args.models_dir / model_id, specs[model_id])
                    vectors, vector_key, embedding_proof = encode_corpus(
                        corpus, corpus_hash, encoder, max_length, matrix["embedding_batch_size"],
                        args.output_dir / "cache", checkpoint, budget, progress,
                    )
                    if vectors.shape[0] != len(corpus):
                        raise ValueError("incomplete_embedding_coverage")
                    store = CachedStore(corpus, corpus_hash, lexical_conn, vectors, vector_key,
                                        encoder, max_length, checkpoint, budget, matrix["candidate_cache_limit"])
                    done = checkpoint.completed(job)
                    completed_count = len(done)
                    proof_by_model = {model_id: {"execution": embedding_proof,
                                                "indexed_documents": vectors.shape[0],
                                                "total_documents": len(corpus),
                                                "coverage_fraction": 1.0,
                                                "passage_token_telemetry": embedding_proof.get("passage_token_telemetry"),
                                                "vector_cache_fingerprint": vector_key}}
                    # Group by reranker so only one encoder and one reranker occupy GPU memory.
                    groups = [(None, [e for e in experiments if not e.rerank]),
                              (matrix["reranker_model"], [e for e in experiments if e.rerank and e.id != "rrf_rerank_english"]),
                              (matrix["alternative_reranker_model"], [e for e in experiments if e.id == "rrf_rerank_english"])]
                    for reranker_id, group in groups:
                        remaining = [(e, case) for e in group for case in cases if (e.id, case["id"]) not in done]
                        if not remaining:
                            if reranker_id:
                                proof_by_model[reranker_id] = checkpoint.get("job_proof:" + job + ":" + reranker_id)
                            continue
                        random.Random(matrix["seed"]).shuffle(remaining)
                        cached_rerank, provider = None, None
                        if reranker_id:
                            budget.check()
                            provider = OnnxCrossEncoder(args.models_dir / reranker_id, specs[reranker_id])
                            def save_proof(proof, model=reranker_id, job_key=job):
                                checkpoint.put("job_proof:" + job_key + ":" + model, proof)
                            cached_rerank = CachedReranker(provider, checkpoint, budget, 512,
                                                          matrix["rerank_batch_size"], on_proof=save_proof)
                        for experiment, case in remaining:
                            budget.check()
                            active_experiment, active_query = experiment.id, case["id"]
                            record = measure_query(store, case, experiment, cached_rerank)
                            checkpoint.save_record(job, record)
                            done.add((experiment.id, case["id"]))
                            completed_count += 1
                            progress("query_evaluation", dataset=dataset_name, embedding_model=model_id,
                                     max_length=max_length, experiment=experiment.id,
                                     done=completed_count, total=len(cases) * len(experiments),
                                     cache_hits=store.hits, cache_misses=store.misses)
                        if cached_rerank:
                            proof_by_model[reranker_id] = cached_rerank.proof
                            checkpoint.put("job_proof:" + job + ":" + reranker_id, cached_rerank.proof)
                        del cached_rerank, provider
                        gc.collect()
                    records = checkpoint.records(job)
                    write_job_report(args.output_dir, job, description, records, experiments,
                                     cases, matrix, checkpoint, proof_by_model)
                    state["completed_jobs"].append(job)
                    atomic_json(state_path, state)
                    del store, vectors, records
                del encoder
                gc.collect()
            lexical_conn.close()
        state["status"] = "completed"
        state["completed_at"] = datetime.now(UTC).isoformat()
        state["real_inference_telemetry"] = checkpoint.timings()
        atomic_json(state_path, state)
        atomic_json(args.output_dir / "progress.json", {"status": "completed", "completed_jobs": len(state["completed_jobs"]),
                                                       "completed_at": state["completed_at"]})
        print(json.dumps({"status": "completed", "jobs": len(state["completed_jobs"])}), flush=True)
        return 0
    except StopRequested as stop:
        stopped_status = "budget_exhausted" if str(stop) == "wall_clock_budget_reached" else "incomplete_stopped"
        state.update(status=stopped_status, stop_reason=str(stop),
                     stopped_at=datetime.now(UTC).isoformat())
        atomic_json(state_path, state)
        atomic_json(args.output_dir / "progress.json", {"status": state["status"], "stop_reason": str(stop),
                                                       "resume": "rerun same command after removing STOP or extending budget"})
        return 2
    except Exception as error:
        checkpoint.failure(active_job, active_experiment, active_query, error)
        state.update(status="incomplete_failed", error_type=type(error).__name__,
                     failed_at=datetime.now(UTC).isoformat())
        atomic_json(state_path, state)
        atomic_json(args.output_dir / "progress.json", {"status": state["status"], "error_type": type(error).__name__,
                                                       "job": active_job, "experiment": active_experiment, "query_id": active_query})
        raise
    finally:
        checkpoint.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models-dir", type=Path, required=True)
    parser.add_argument("--data-dir", type=Path, default=BACKEND / "data/public-rag")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--models-manifest", type=Path, default=BACKEND / "samples/rag_ablation/public_models.json")
    parser.add_argument("--matrix", type=Path, default=BACKEND / "samples/rag_ablation/public_gpu_matrix.json")
    parser.add_argument("--budget-hours", type=float)
    parser.add_argument("--pilot", action="store_true")
    parser.add_argument("--pilot-models", nargs="+", help="Pilot only these pinned model IDs, e.g. e5_small")
    args = parser.parse_args()
    matrix = read_json(args.matrix)
    specs = {spec["id"]: spec for spec in read_json(args.models_manifest)["models"]}
    if args.pilot_models and (not args.pilot or set(args.pilot_models) - set(specs)):
        parser.error("--pilot-models requires --pilot and known pinned model IDs")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    if args.budget_hours is not None and (not math.isfinite(args.budget_hours) or args.budget_hours <= 0):
        parser.error("budget hours must be positive")
    if not math.isfinite(matrix["budget_hours"]) or matrix["budget_hours"] <= 0:
        parser.error("matrix budget hours must be finite and positive")
    lock_path = args.output_dir / "runner.lock"
    try:
        # Never run two writers on the same state; explicit stale-lock removal is required after a hard kill.
        with lock_path.open("x", encoding="utf-8") as lock:
            lock.write(str(os.getpid()))
    except FileExistsError as error:
        raise RuntimeError("runner_lock_exists_verify_process_before_removing") from error
    try:
        return pilot(args, matrix, specs) if args.pilot else run(args, matrix, specs)
    finally:
        lock_path.unlink(missing_ok=True)


if __name__ == "__main__":
    raise SystemExit(main())
